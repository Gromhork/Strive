"""Writes lib/l10n/gen/l10n_pairs.dart: every simple (non-plural) message as an (en, de) pair.

Used by lib/l10n/relocalize.dart to translate texts that were stored in Firestore in the
language that was active when they were created (generated plans, built-in programs).
Run after changing the ARB files (tool/add_l10n.py does it automatically).
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
en = json.load(open(os.path.join(ROOT, 'lib', 'l10n', 'app_en.arb'), encoding='utf-8'))
de = json.load(open(os.path.join(ROOT, 'lib', 'l10n', 'app_de.arb'), encoding='utf-8'))
BS = chr(92)


def q(s):
    s = s.replace(BS, BS + BS).replace("'", BS + "'").replace('$', BS + '$').replace('\n', BS + 'n')
    return "'" + s + "'"


rows = []
for k, v in en.items():
    if k.startswith('@') or not isinstance(v, str) or k not in de:
        continue
    d = de[k]
    if ', plural,' in v or ', select,' in v or ', plural,' in d or v == d:
        continue
    rows.append(f'  ({q(v)}, {q(d)}),')
out = ('// GENERATED by tool/gen_l10n_pairs.py - do not edit.\n\n'
       '/// (English, German) message pairs from the ARB files.\n'
       'const l10nPairs = <(String, String)>[\n' + '\n'.join(rows) + '\n];\n')
open(os.path.join(ROOT, 'lib', 'l10n', 'gen', 'l10n_pairs.dart'), 'w', encoding='utf-8', newline='\n').write(out)
print('pairs', len(rows))
